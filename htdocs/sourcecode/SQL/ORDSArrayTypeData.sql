END;

BEGIN
    pkg_element_entries.update_entry(
        p_entry_id => :id,
        p_payload => :body
    );
END;


CREATE OR REPLACE PACKAGE pkg_element_entries AS
    -- Procedure to Insert a New Element Entry
    PROCEDURE create_entry (
        p_payload IN CLOB,
        p_entry_id OUT NUMBER
    );

    -- Procedure to Update an Existing Element Entry
    PROCEDURE update_entry (
        p_entry_id IN NUMBER,
        p_payload IN CLOB
    );
END pkg_element_entries;
/

CREATE OR REPLACE PACKAGE BODY pkg_element_entries AS

    PROCEDURE create_entry (
        p_payload IN CLOB,
        p_entry_id OUT NUMBER
    ) IS
        l_employee_id       VARCHAR2(50);
        l_element_id        VARCHAR2(100);
        l_start_date        DATE;
    -- Parse Header Fields
    BEGIN
        SELECT 
            JSON_VALUE(p_payload, '$.employeeId'),
            JSON_VALUE(p_payload, '$.elementId'),
            TO_DATE(JSON_VALUE(p_payload, '$.effectiveStartDate'), 'YYYY-MM-DD')
        INTO 
            l_employee_id, l_element_id, l_start_date
        FROM DUAL;

        -- Insert into Header Table
        INSERT INTO element_entry_headers (employee_id, element_id, effective_start_date)
        VALUES (l_employee_id, l_element_id, l_start_date)
        RETURNING entry_id INTO p_entry_id;

        -- Insert Dynamic Input Values using JSON_TABLE
        INSERT INTO element_entry_values (entry_id, input_name, input_value)
        SELECT 
            p_entry_id,
            jt.input_name,
            jt.input_value
        FROM JSON_TABLE(p_payload, '$.inputValues[*]'
            COLUMNS (
                input_name  VARCHAR2(100) PATH '$.name',
                input_value VARCHAR2(4000) PATH '$.value'
            )
        ) jt;

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END create_entry;

    PROCEDURE update_entry (
        p_entry_id IN NUMBER,
        p_payload IN CLOB
    ) IS
        l_start_date DATE;
    BEGIN
        -- Update Header details if needed
        SELECT TO_DATE(JSON_VALUE(p_payload, '$.effectiveStartDate'), 'YYYY-MM-DD')
        INTO l_start_date
        FROM DUAL;

        UPDATE element_entry_headers
        SET effective_start_date = NVL(l_start_date, effective_start_date)
        WHERE entry_id = p_entry_id;

        -- Refresh Dynamic Input Values: Delete old entries and insert updated ones
        DELETE FROM element_entry_values WHERE entry_id = p_entry_id;

        INSERT INTO element_entry_values (entry_id, input_name, input_value)
        SELECT 
            p_entry_id,
            jt.input_name,
            jt.input_value
        FROM JSON_TABLE(p_payload, '$.inputValues[*]'
            COLUMNS (
                input_name  VARCHAR2(100) PATH '$.name',
                input_value VARCHAR2(4000) PATH '$.value'
            )
        ) jt;

        COMMIT;
    EXCEPTION
        WHEN OTHERS THEN
            ROLLBACK;
            RAISE;
    END update_entry;

END pkg_element_entries;
