-- Header Table
CREATE TABLE element_entry_headers (
    entry_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id VARCHAR2(50),
    element_id VARCHAR2(100),
    effective_start_date DATE,
    created_at TIMESTAMP DEFAULT SYSTIMESTAMP
);

-- Child Table for Dynamic Input Values
CREATE TABLE element_entry_values (
    value_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entry_id NUMBER REFERENCES element_entry_headers(entry_id) ON DELETE CASCADE,
    input_name VARCHAR2(100),
    input_value VARCHAR2(4000)
);

-- ORDS Handlers

BEGIN
    pkg_element_entries.create_entry(
        p_payload => :body,
        p_entry_id => :id
    );
